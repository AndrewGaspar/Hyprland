#!/usr/bin/env bash
# Generate a nested-session Hyprland config that mirrors the user's Omarchy
# desktop (keybinds, look'n'feel, theme) but is SAFE to run as a NESTED dev
# compositor for the HypXRland preview (scripts/preview-xr.sh --conf ...).
#
# What this produces (under ~/.config/hypr/xr-nested/):
#   nested.lua    - the generated Lua config (Hyprland 0.57+ reads Lua only):
#                   require()s the WANTED Omarchy/user modules, skips anything that
#                   mutates global session state or launches service-like daemons,
#                   adds a PATH shim + XR essentials.
#   bin/uwsm-app  - a shim that execs its command directly instead of routing
#                   through the host's wayland-wm-app-daemon / systemd session
#                   (so keybind-launched apps land in the NESTED session).
#
# Re-run this whenever your Omarchy config changes to keep nested.lua in sync
# (it REQUIRES the live modules, so most edits need no regeneration; regenerate
# only to pick up structural changes or a new $PATH).
#
# Targets the Lua Omarchy layout (Omarchy 4: $OMARCHY_PATH/default/hypr/*.lua,
# loaded through default/hypr/bootstrap.lua, user modules as ~/.config/hypr/*.lua
# = `hypr.<name>`). Every module is required through a not-found-tolerant guard,
# so a module a given Omarchy version lacks is skipped (and printed) instead of
# aborting the nested config.
#
# Machine-agnostic: derives $HOME / $PATH at runtime, writes no hardcoded paths
# for other machines. The generated file lives in your home and is specific to
# this machine by design.

set -euo pipefail

HOME_DIR="${HOME:?HOME must be set}"
OUT_DIR="$HOME_DIR/.config/hypr/xr-nested"
SHIM_DIR="$OUT_DIR/bin"
NESTED_CONF="$OUT_DIR/nested.lua"

# Omarchy's tree: $OMARCHY_PATH if set (bootstrap.lua reads the same variable), else
# the per-user install, else the package location bootstrap.lua itself falls back to.
OMARCHY_ROOT="${OMARCHY_PATH:-}"
if [[ -z $OMARCHY_ROOT ]]; then
    if [[ -f $HOME_DIR/.local/share/omarchy/default/hypr/bootstrap.lua ]]; then
        OMARCHY_ROOT="$HOME_DIR/.local/share/omarchy"
    else
        OMARCHY_ROOT="/usr/share/omarchy"
    fi
fi
[[ -f $OMARCHY_ROOT/default/hypr/bootstrap.lua ]] || {
    echo "no Lua Omarchy found at $OMARCHY_ROOT (default/hypr/bootstrap.lua missing)." >&2
    echo "Hyprland 0.57+ reads Lua configs only; this generator mirrors a Lua Omarchy (4.x)." >&2
    exit 1
}

mkdir -p "$SHIM_DIR"

# --------------------------------------------------------------------------
# 1. uwsm-app shim
# --------------------------------------------------------------------------
# Omarchy keybinds launch apps via `uwsm-app -- <cmd>` (and `setsid uwsm-app --
# <cmd>` from omarchy-launch-* scripts). The real uwsm-app hands the command to
# the HOST's wayland-wm-app-daemon.service + systemd user session, so the app is
# spawned by the HOST session (wrong WAYLAND_DISPLAY, host env) instead of the
# nested compositor. This shim just execs the command directly: apps then
# inherit the nested compositor's WAYLAND_DISPLAY and land in the nested session.
cat > "$SHIM_DIR/uwsm-app" <<'SHIM'
#!/bin/sh
# Nested-session uwsm-app shim (generated by gen-omarchy-xr-conf.sh).
# Real uwsm-app routes through the host wayland-wm-app-daemon + systemd session;
# here we exec the target command directly so it inherits the nested compositor's
# WAYLAND_DISPLAY. Handles the Omarchy call forms:
#   uwsm-app -- CMD ARGS
#   uwsm-app -t service -- CMD          (any uwsm 'app' options before --)
#   setsid uwsm-app -- CMD              (setsid execs us; nothing special)
#   uwsm-app -- env VAR=x CMD ...       (env is a real binary, exec'd normally)
# Strategy: drop everything up to and including the first "--", exec the rest.
# Daemon-control pseudo-args are no-oped so nothing tries to poke the host daemon.

case "${1:-}" in
    ping) echo pong; exit 0 ;;
    stop) exit 0 ;;
esac

# Is there a "--" separator? (Omarchy always uses one.)
has_sep=0
for a in "$@"; do
    [ "$a" = "--" ] && { has_sep=1; break; }
done

if [ "$has_sep" = 1 ]; then
    while [ "$#" -gt 0 ]; do
        arg="$1"; shift
        [ "$arg" = "--" ] && break
    done
fi

[ "$#" -eq 0 ] && { echo "uwsm-app shim: nothing to exec" >&2; exit 1; }
exec "$@"
SHIM
chmod +x "$SHIM_DIR/uwsm-app"

# --------------------------------------------------------------------------
# NOTE on DBus single-instance apps (no override needed anymore)
# --------------------------------------------------------------------------
# preview-xr.sh launches the nested Hyprland under `dbus-run-session`, so the
# nested session has its OWN private DBus session bus. GApplication/DBus
# single-instance apps (ghostty, walker, mako, the browser, nautilus, obsidian…)
# therefore find NO existing instance on this fresh bus and start a NEW one inside
# the nested session — no more delegating to the HOST instance. That means the old
# per-terminal `--gtk-single-instance=false` override is unnecessary: the stock
# `uwsm-app -- xdg-terminal-exec` bind (via the shim above) already lands nested.
# --------------------------------------------------------------------------
# 2. nested.lua
# --------------------------------------------------------------------------
# Prepend the shim dir to the PATH captured now. The nested compositor's hl.env()
# setenv()s this and every keybind-launched app inherits the shim-first PATH.
PATH_LITERAL="$SHIM_DIR:$PATH"

cat > "$NESTED_CONF" <<CONF
-- ==========================================================================
-- Omarchy-mirror nested config for the HypXRland preview.
-- GENERATED by scripts/gen-omarchy-xr-conf.sh — do not edit by hand; re-run it.
--
-- Launch with:  scripts/preview-xr.sh --conf $NESTED_CONF
--
-- Mirrors the user's Omarchy desktop (keybinds / look'n'feel / theme) while
-- excluding everything that mutates global session state or starts daemons:
--   EXCLUDED  default.hypr.autostart   (systemctl/dbus import-environment, the
--                                       Omarchy shell, first-run, power profiles,
--                                       monitor-watch, udiskie, post-boot hooks)
--   EXCLUDED  hypr.autostart           (the user's own autostart)
--   EXCLUDED  hypr.monitors            (host monitor layout; nested has its own
--                                       WAYLAND-1 + XR outputs)
--
-- PRIVATE DBus session bus: preview-xr.sh launches this nested Hyprland under
-- dbus-run-session, so the whole nested session (and every keybind-launched app,
-- which inherits DBUS_SESSION_BUS_ADDRESS through Hyprland's fork/exec) has its OWN
-- session bus. DBus/GApplication singletons (ghostty, walker, mako, browser,
-- nautilus, obsidian, web-apps) therefore start FRESH nested instead of routing to
-- their already-running HOST instances. Side effects (all fine for a preview):
-- nested notifications go to the nested mako (below), not the host;
-- xdg-desktop-portal dbus-activates fresh on this bus (pickers/screencast may be
-- limited); host DBus services (NetworkManager applet, etc.) are absent.
-- ==========================================================================

-- Route keybind app-launches through the uwsm-app shim so they land in THIS
-- nested session instead of the host session (shim dir first on PATH).
hl.env("PATH", [==[$PATH_LITERAL]==])

-- Omarchy's module path (state, ~/.config, then the Omarchy tree), exactly as the
-- desktop's own hyprland.lua sets it up.
dofile([==[$OMARCHY_ROOT/default/hypr/bootstrap.lua]==])
-- bootstrap.lua resolves the tree from \$OMARCHY_PATH at load time; pin the one found at
-- generation time too, so a nested launch without that variable still finds the modules.
package.path = [==[$OMARCHY_ROOT/?.lua;]==] .. package.path

-- require() that skips a module this Omarchy version does not have (and says so)
-- instead of failing the whole nested config. Errors INSIDE a module that exists
-- still surface as config errors.
local function want(module)
    if package.searchpath(module, package.path) then
        return require(module)
    end
    print("nested.lua: no module " .. module .. ", skipped")
end

-- Nested output: one Wayland window on the host desktop (preview default; the
-- host monitor layout in hypr.monitors is intentionally NOT required).
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = "1" })

-- ---- Omarchy helpers (the o.* functions the other modules use) ----
want("default.hypr.helpers")

-- ---- Look'n'feel / theme / input (Omarchy defaults + user overrides) ----
-- Required live, so edits to these files show up on the next nested launch.
want("default.hypr.envs")
want("default.hypr.looknfeel")
want("default.hypr.input")
want("default.hypr.windows")
want("omarchy.current.theme.hyprland")
want("hypr.input")
want("hypr.looknfeel")

-- ---- Keybinds (Omarchy defaults + user) ----
want("default.hypr.bindings.media")
want("default.hypr.bindings.clipboard")
want("default.hypr.bindings.tiling")
want("default.hypr.bindings.utilities")
want("hypr.bindings")

-- ---- Permanent config toggles (harmless flags) ----
want("default.hypr.toggles")

-- ---- Per-session cosmetics (SAFE: plain exec at start, no uwsm/systemd/dbus) ----
-- waybar gives a top bar, swaybg the themed wallpaper, mako the nested notification
-- daemon (safe: the nested session owns org.freedesktop.Notifications on its OWN
-- private bus). Each runs only if installed. NOT launched: hypridle, fcitx5, the
-- polkit agent, or anything systemctl/dbus-* (global state / unwanted in a preview).
hl.on("hyprland.start", function()
    hl.exec_cmd("command -v waybar >/dev/null && waybar")
    hl.exec_cmd("command -v swaybg >/dev/null && swaybg -i $HOME_DIR/.config/omarchy/current/background -m fill")
    hl.exec_cmd("command -v mako >/dev/null && mako")
end)

-- ==========================================================================
-- HypXRland XR essentials (equivalent of scripts/preview-xr.lua).
-- preview-xr.sh layers openxr.gpu / overlay / blend_mode on top of this file.
-- ==========================================================================
hl.config({ openxr = { enabled = true } })

-- A world-locked monitor straight ahead at eye height...
hl.xr_monitor("XR-main, 1920x1080@60, anchor:local pos:0,1.5,-1.5 yaw:0, size:1.6")
-- ...and a head-leashed side panel that springs along with your view.
hl.xr_monitor("XR-side, 1280x720@60, anchor:head offset:0.9,0,-1.2, size:0.9")

-- ---- XR keybinds (SUPER+ALT + arrow keys are free in the Omarchy layout) ----
-- Lifecycle
hl.bind("SUPER + ALT + C", hl.dsp.xrmonitor("create XR-extra 1280x720 anchor:body offset:0,-0.3,-1.0"), { description = "Create XR monitor" })
hl.bind("SUPER + ALT + D", hl.dsp.xrmonitor("destroy XR-extra"), { description = "Destroy XR monitor" })
-- Selection (which XR monitor the pose verbs act on)
hl.bind("SUPER + ALT + N", hl.dsp.xrmonitor("select next"), { description = "Select next XR monitor" })
hl.bind("SUPER + ALT + P", hl.dsp.xrmonitor("select prev"), { description = "Select previous XR monitor" })
-- Pose: rotate / distance on the arrow keys
hl.bind("SUPER + LEFT", hl.dsp.xrmonitor("rotate -15"), { description = "Rotate XR monitor left" })
hl.bind("SUPER + RIGHT", hl.dsp.xrmonitor("rotate 15"), { description = "Rotate XR monitor right" })
hl.bind("SUPER + UP", hl.dsp.xrmonitor("distance 0.25"), { description = "Push XR monitor farther" })
hl.bind("SUPER + DOWN", hl.dsp.xrmonitor("distance -0.25"), { description = "Pull XR monitor closer" })
hl.bind("SUPER + HOME", hl.dsp.xrmonitor("center"), { description = "Recenter XR monitor on gaze" })
-- Quit the nested compositor (SUPER+Q stays Omarchy's "close window").
hl.bind("SUPER + SHIFT + Q", hl.dsp.exit(), { description = "Exit nested session" })
CONF

echo "generated:"
echo "  $NESTED_CONF"
echo "  $SHIM_DIR/uwsm-app  (uwsm-app shim)"
echo
echo "launch the nested Omarchy-mirror preview with:"
echo "  scripts/preview-xr.sh --conf $NESTED_CONF"
