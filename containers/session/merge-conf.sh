#!/usr/bin/env bash
# In-container: generate the HypXRland session launch config (the preview-xr.sh
# model, adapted for the container). Hyprland 0.57+ reads Lua configs only, so this
# emits Lua:
#   require(<base>)          the base session config (a Lua file): ~/.config/hypr/
#                            hyprland.lua, or a user config the wrapper bind-mounted
#                            via --conf
#   hl.monitor{ output="" }  neutralizes any host-specific monitor layout from the
#                            base config (the container nests into ONE wayland
#                            output)
#   hl.config{ openxr={…} }  enabled + gpu pin + optional overlay/passthrough
#   hl.xr_monitor(…)         the two default XR monitors (mirrors preview-xr.lua)
#   hl.bind(…)               the container-session XR keybinds (unless XR_BINDS=0)
#
# Env inputs:
#   XR_BASE_CONF    base config to require (default ~/.config/hypr/hyprland.lua). Must
#                   be Lua. When the DEFAULT is absent (an image seeded with a classic
#                   .conf-only Omarchy, e.g. v3.8.2), the session comes up WITHOUT a
#                   base desktop config and says so; an explicit non-Lua --conf is an
#                   error.
#   XR_GPU_NODE     render node for openxr.gpu (resolved by the wrapper; e.g.
#                   a /dev/dri/renderD* path)
#   XR_OVERLAY      1 -> openxr.overlay = true (XR_EXTX_overlay; the --env hook)
#   XR_PASSTHROUGH  1 -> openxr.blend_mode = "alpha" (composite over passthrough) plus
#                   the luma-key default (black_alpha) that makes it read as AR.
#                   Defaulted ON for --wivrn by the wrapper (xr-container.sh).
#   XR_BINDS        1 (default) -> append the container-session XR keybind block;
#                   0 -> emit none (a --conf base config that binds the same chords
#                   would double-fire them).
#
# Usage: merge-conf.sh <output-file>   (writes the config there; echoes the path)
set -euo pipefail

OUT="${1:?usage: merge-conf.sh <output-file>}"
DEFAULT_BASE="$HOME/.config/hypr/hyprland.lua"
BASE="${XR_BASE_CONF:-$DEFAULT_BASE}"
if [[ ! -f $BASE ]]; then
    if [[ $BASE == "$DEFAULT_BASE" ]]; then
        echo "merge-conf: no Lua base config at $BASE." >&2
        [[ -f $HOME/.config/hypr/hyprland.conf ]] \
            && echo "merge-conf: the image seeds a classic hyprland.conf, which Hyprland 0.57+ cannot read." >&2
        echo "merge-conf: the session starts WITHOUT a base desktop config (pass --conf <file.lua> for one)." >&2
        BASE=""
    else
        echo "merge-conf: base config not found: $BASE" >&2
        exit 1
    fi
elif [[ $BASE != *.lua ]]; then
    echo "merge-conf: base config must be Lua (Hyprland 0.57+ has no classic .conf front end): $BASE" >&2
    exit 1
fi

{
    echo "-- Generated by containers/session/merge-conf.sh — do not edit by hand."
    if [[ -n $BASE ]]; then
        echo "-- Base session config (full desktop, or a --conf override):"
        echo "require([==[$BASE]==])"
    else
        echo "-- (no Lua base config available — bare XR session)"
    fi
    echo ""
    echo "-- The container nests into ONE wayland output; neutralize any host monitor"
    echo "-- layout from the base (the Omarchy monitors config pins scale 2 / auto-auto)."
    echo 'hl.monitor({ output = "", mode = "preferred", position = "auto", scale = "1" })'
    echo ""
    echo "hl.config({"
    echo "    openxr = {"
    echo "        enabled = true,"
    [[ -n ${XR_GPU_NODE:-} ]]      && echo "        gpu = [==[$XR_GPU_NODE]==],"
    [[ ${XR_OVERLAY:-0} == 1 ]]    && echo "        overlay = true,"
    if [[ ${XR_PASSTHROUGH:-0} == 1 ]]; then
        cat <<'PASSTHROUGH'

        -- Passthrough (container-session default with a real headset; --no-passthrough
        -- opts out). Composite the monitors over the room instead of the opaque VR
        -- void. Read once at session start — flip live with:
        --   hyprctl eval 'hl.config({ openxr = { blend_mode = "opaque" } })'
        --   hyprctl openxr disable && hyprctl openxr enable
        -- A runtime that can't do alpha (the windowed Monado) falls back to its
        -- preferred mode with one warning, so this is never fatal.
        blend_mode = "alpha",

        -- Luma-keyed transparency ("black-as-alpha"), mirroring the daily-driver
        -- config: black desktop pixels dissolve into the room so a monitor reads as
        -- an AR overlay; 0.2 keeps a faint scrim behind text. Hot — retune in-headset
        -- with `hyprctl eval 'hl.config({ openxr = { black_alpha = <n> } })'` (and
        -- black_alpha_knee, 0.10) and paste the winner into your own config.
        -- Force-disabled under opaque.
        black_alpha = 0.2,
PASSTHROUGH
    fi
    echo "    },"
    echo "})"
    echo ""
    echo "-- Two default XR monitors (mirrors scripts/preview-xr.lua):"
    echo "--   world-locked panel straight ahead at eye height,"
    echo 'hl.xr_monitor("XR-main, 1920x1080@60, anchor:local pos:0,1.5,-1.5 yaw:0, size:1.6")'
    echo "--   and a head-leashed side panel that springs to follow your view."
    echo 'hl.xr_monitor("XR-side, 1280x720@60, anchor:head offset:0.9,0,-1.2, size:0.9")'

    # ---- container-session XR keybinds -------------------------------------
    # Defaults so an in-headset test session can drive the extension without
    # hand-writing a config every time. Chords mirror the daily-driver
    # ~/.config/hypr/hyprland-xr.lua (muscle memory transfers) and every one of
    # them is FREE in the stock Omarchy bindings the base config requires.
    if [[ ${XR_BINDS:-1} == 1 ]]; then
        cat <<'BINDS'

-- ---- Container-session XR keybinds (defaults; `--no-binds` omits this block) --
-- Dispatcher vocabulary: docs/openxr/05-configuration.md §4.
-- Chords mirror the daily-driver ~/.config/hypr/hyprland-xr.lua so muscle
-- memory transfers.
--
-- Each chord is unbound first. Hyprland fires EVERY bind matching a chord,
-- not just the last one, so a chord the base config already claims would run
-- both actions — and a doubled `toggle` verb would cancel itself out. The seeded
-- Omarchy config really does claim one of these (SUPER+SHIFT+G = Signal). Pass
-- `--no-binds` to keep the base config's bindings instead of these.
for _, chord in ipairs({
    "SUPER + ALT + M", "SUPER + SHIFT + G", "SUPER + ALT + equal", "SUPER + ALT + minus",
    "SUPER + Home", "SUPER + SHIFT + Home", "SUPER + ALT + N", "SUPER + ALT + SHIFT + N",
    "SUPER + ALT + H", "SUPER + ALT + R",
}) do
    hl.unbind(chord)
end

-- Show/hide every XR monitor quad — session, outputs, workspaces and anchors all
-- stay intact (and hidden quads leave ray hit-testing).
hl.bind("SUPER + ALT + M", hl.dsp.xrmonitor("view toggle"), { description = "Toggle XR monitor view" })

-- Gaze grab: look at a monitor, tap to carry it with your gaze, tap to drop it.
hl.bind("SUPER + SHIFT + G", hl.dsp.xrmonitor("gazegrab"), { description = "Gaze-grab the monitor you are looking at" })
-- Push/pull the gaze-carried (or gaze-selected) monitor along the gaze ray.
hl.bind("SUPER + ALT + equal", hl.dsp.xrmonitor("gazepush 0.1"), { repeating = true, description = "Push the gazed XR monitor away" })
hl.bind("SUPER + ALT + minus", hl.dsp.xrmonitor("gazepush -0.1"), { repeating = true, description = "Pull the gazed XR monitor closer" })

-- Re-place the selected monitor centered in view at openxr.default_distance.
hl.bind("SUPER + Home", hl.dsp.xrmonitor("center"), { description = "Recenter the selected XR monitor" })
-- Re-derive the 2D monitor plane (mouse crossing / directional focus) from where
-- the quads actually float right now. Moves nothing.
hl.bind("SUPER + SHIFT + Home", hl.dsp.xrmonitor("sync"), { description = "Re-sync the 2D XR layout" })

-- One scratch monitor to create and throw away. (The daily config mints the
-- lowest free XR-<n> from a helper script; the bare dispatcher keeps the
-- container dependency-free — `hyprctl openxr create <name>` for more.)
hl.bind("SUPER + ALT + N", hl.dsp.xrmonitor("create XR-extra"), { description = "Create the XR-extra scratch monitor" })
hl.bind("SUPER + ALT + SHIFT + N", hl.dsp.xrmonitor("destroy XR-extra"), { description = "Destroy the XR-extra scratch monitor" })

-- Hand tracking on/off at the keyboard (controllers are never gated by this).
hl.bind("SUPER + ALT + H", hl.dsp.xrmonitor("handinput toggle"), { description = "Toggle XR hand input" })

-- Restart the XR session in place: how you apply start-scoped openxr settings
-- (blend_mode, overlay, gpu, runtime_json) without restarting the container.
hl.bind("SUPER + ALT + R", hl.dsp.exec_cmd("hyprctl openxr disable && hyprctl openxr enable"), { description = "Restart the XR session" })
BINDS
    fi
} > "$OUT"

echo "$OUT"
